-- 7a. Audit columns: created_* only on insert, updated_* on every change.
create function set_audit_fields() returns trigger
language plpgsql set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.created_at := now();
    new.created_by := auth.uid();
  else
    new.created_at := old.created_at;   -- never let an update rewrite creation info
    new.created_by := old.created_by;
  end if;
  new.updated_at := now();
  new.updated_by := auth.uid();
  return new;
end $$;

-- 7b. Audit log: copy every insert / update / delete into audit_log.
--     SECURITY DEFINER so it can write audit_log even though normal users cannot.
--     TG_ARGV[0] = name of the primary key column.
create function write_audit_log() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into audit_log (table_name, record_id, action, changed_by, old_data, new_data)
  values (
    tg_table_name,
    coalesce(to_jsonb(new), to_jsonb(old)) ->> tg_argv[0],
    tg_op,
    auth.uid(),
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end
  );
  return coalesce(new, old);
end $$;

-- Attach both triggers to every core / extension table.
do $$
declare
  t record;
begin
  for t in
    select * from (values
      ('farmer', 'farmer_id'), ('farm', 'farm_id'), ('crop', 'crop_id'),
      ('planting', 'planting_id'), ('harvest', 'harvest_id'),
      ('buyer', 'buyer_id'), ('sale', 'sale_id'),
      ('input_item', 'input_id'), ('input_usage', 'usage_id')
    ) as x(tbl, pk)
  loop
    execute format('create trigger trg_%1$s_audit_fields before insert or update on %1$I
                    for each row execute function set_audit_fields()', t.tbl);
    execute format('create trigger trg_%1$s_audit_log after insert or update or delete on %1$I
                    for each row execute function write_audit_log(%2$L)', t.tbl, t.pk);
  end loop;
end $$;

-- 7c. Business rules that need data from another table (a CHECK constraint
--     can only see its own row). Errors use SQLSTATE P0001 and a plain-English
--     message, which the app shows to the user as-is.

-- Planting: area must fit in the farm; changing the date must not break
-- existing harvests or input records.
create function check_planting_rules() returns trigger
language plpgsql set search_path = public as $$
declare
  v_farm_area numeric;
begin
  select area_hectares into v_farm_area from farm where farm_id = new.farm_id;
  if new.area_planted > v_farm_area then
    raise exception 'Area planted (% ha) cannot be larger than the farm area (% ha).', new.area_planted, v_farm_area;
  end if;
  if tg_op = 'UPDATE' then
    if exists (select 1 from harvest h where h.planting_id = new.planting_id and h.harvest_date < new.planting_date) then
      raise exception 'This planting already has a harvest dated before the new planting date.';
    end if;
    if exists (select 1 from input_usage u where u.planting_id = new.planting_id and u.usage_date < new.planting_date) then
      raise exception 'This planting already has input usage dated before the new planting date.';
    end if;
  end if;
  return new;
end $$;
create trigger trg_planting_rules before insert or update on planting
  for each row execute function check_planting_rules();

-- Farm: cannot shrink below the area of any of its plantings.
create function check_farm_rules() returns trigger
language plpgsql set search_path = public as $$
begin
  if exists (select 1 from planting p where p.farm_id = new.farm_id and p.area_planted > new.area_hectares) then
    raise exception 'Farm area cannot be smaller than the area of an existing planting on this farm.';
  end if;
  return new;
end $$;
create trigger trg_farm_rules before update on farm
  for each row execute function check_farm_rules();

-- Harvest: cannot be before planting; cannot drop below what is already sold.
create function check_harvest_rules() returns trigger
language plpgsql set search_path = public as $$
declare
  v_planting_date date;
  v_sold numeric;
begin
  select planting_date into v_planting_date from planting where planting_id = new.planting_id;
  if new.harvest_date < v_planting_date then
    raise exception 'Harvest date cannot be earlier than the planting date (%).', v_planting_date;
  end if;
  if tg_op = 'UPDATE' then
    select coalesce(sum(quantity_kg), 0) into v_sold from sale where harvest_id = new.harvest_id;
    if new.quantity_kg < v_sold then
      raise exception 'Harvest quantity cannot be less than the % kg already sold.', v_sold;
    end if;
    if exists (select 1 from sale s where s.harvest_id = new.harvest_id and s.sale_date < new.harvest_date) then
      raise exception 'This harvest already has a sale dated before the new harvest date.';
    end if;
  end if;
  return new;
end $$;
create trigger trg_harvest_rules before insert or update on harvest
  for each row execute function check_harvest_rules();

-- Sale: not before the harvest, and total sold cannot exceed the harvest.
create function check_sale_rules() returns trigger
language plpgsql set search_path = public as $$
declare
  v_harvest_date date;
  v_harvest_qty  numeric;
  v_other_sold   numeric;
begin
  select harvest_date, quantity_kg into v_harvest_date, v_harvest_qty
  from harvest where harvest_id = new.harvest_id;
  if new.sale_date < v_harvest_date then
    raise exception 'Sale date cannot be earlier than the harvest date (%).', v_harvest_date;
  end if;
  select coalesce(sum(quantity_kg), 0) into v_other_sold
  from sale where harvest_id = new.harvest_id and sale_id <> coalesce(new.sale_id, -1);
  if v_other_sold + new.quantity_kg > v_harvest_qty then
    raise exception 'Only % kg of this harvest is still available to sell.', v_harvest_qty - v_other_sold;
  end if;
  return new;
end $$;
create trigger trg_sale_rules before insert or update on sale
  for each row execute function check_sale_rules();

-- Input usage: not before the planting date.
create function check_input_usage_rules() returns trigger
language plpgsql set search_path = public as $$
declare
  v_planting_date date;
begin
  select planting_date into v_planting_date from planting where planting_id = new.planting_id;
  if new.usage_date < v_planting_date then
    raise exception 'Usage date cannot be earlier than the planting date (%).', v_planting_date;
  end if;
  return new;
end $$;
create trigger trg_input_usage_rules before insert or update on input_usage
  for each row execute function check_input_usage_rules();

-- 7d. Profiles: create one automatically when a user is added in Supabase Auth.
create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profile (user_id, full_name, email)
  values (new.id, coalesce(nullif(new.raw_user_meta_data ->> 'full_name', ''), new.email), new.email)
  on conflict (user_id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function handle_new_user();

-- Keep updated_at current and always keep at least one Administrator.
create function check_profile_rules() returns trigger
language plpgsql set search_path = public as $$
begin
  new.updated_at := now();
  if old.role_id = 1 and new.role_id <> 1
     and (select count(*) from profile where role_id = 1) <= 1 then
    raise exception 'The system must keep at least one Administrator.';
  end if;
  return new;
end $$;
create trigger trg_profile_rules before update on profile
  for each row execute function check_profile_rules();

-- Users who existed before this script ran also get a profile.
insert into profile (user_id, full_name, email)
select id, coalesce(nullif(raw_user_meta_data ->> 'full_name', ''), email), email
from auth.users
on conflict (user_id) do nothing;


-- =====================================================================
-- 8. LIST VIEWS  (JOINs used by the data tables in the app)
--    security_invoker = true  ->  Row Level Security of the caller applies.
--    The app READS from these views and WRITES to the base tables.
-- =====================================================================

create view v_farmer_list with (security_invoker = true) as
select f.*,
       f.first_name || ' ' || f.last_name as full_name,
       (select count(*) from farm fm where fm.farmer_id = f.farmer_id) as farm_count
from farmer f;

create view v_farm_list with (security_invoker = true) as
select fm.*,
       fr.first_name || ' ' || fr.last_name as farmer_name,
       st.soil_type_name,
       it.irrigation_type_name
from farm fm
join farmer          fr on fr.farmer_id          = fm.farmer_id
join soil_type       st on st.soil_type_id       = fm.soil_type_id
join irrigation_type it on it.irrigation_type_id = fm.irrigation_type_id;

create view v_crop_list with (security_invoker = true) as
select c.*,
       cc.category_name,
       s.season_name
from crop c
join crop_category cc on cc.category_id = c.category_id
join season        s  on s.season_id    = c.season_id;

create view v_planting_list with (security_invoker = true) as
select p.*,
       fm.farm_name,
       fm.location,
       fr.first_name || ' ' || fr.last_name as farmer_name,
       c.crop_name,
       c.variety,
       c.crop_name || ' (' || c.variety || ')' as crop_label,
       ps.status_name
from planting p
join farm            fm on fm.farm_id   = p.farm_id
join farmer          fr on fr.farmer_id = fm.farmer_id
join crop            c  on c.crop_id    = p.crop_id
join planting_status ps on ps.status_id = p.status_id;

create view v_harvest_list with (security_invoker = true) as
select h.*,
       p.planting_date,
       fm.farm_name,
       fm.location,
       fr.first_name || ' ' || fr.last_name as farmer_name,
       c.crop_name,
       c.crop_name || ' (' || c.variety || ')' as crop_label,
       qg.grade_name,
       hr.remark_description,
       round(h.quantity_kg * h.selling_price_per_kg, 2) as estimated_value,
       (select coalesce(sum(s.quantity_kg), 0) from sale s where s.harvest_id = h.harvest_id) as sold_kg
from harvest h
join planting       p  on p.planting_id = h.planting_id
join farm           fm on fm.farm_id    = p.farm_id
join farmer         fr on fr.farmer_id  = fm.farmer_id
join crop           c  on c.crop_id     = p.crop_id
join quality_grade  qg on qg.grade_id   = h.grade_id
join harvest_remark hr on hr.remark_id  = h.remark_id;

create view v_buyer_list with (security_invoker = true) as
select b.*, bt.buyer_type_name
from buyer b
join buyer_type bt on bt.buyer_type_id = b.buyer_type_id;

create view v_sale_list with (security_invoker = true) as
select s.*,
       b.buyer_name,
       h.harvest_date,
       fm.farm_name,
       c.crop_name,
       round(s.quantity_kg * s.price_per_kg, 2) as amount
from sale s
join buyer    b  on b.buyer_id     = s.buyer_id
join harvest  h  on h.harvest_id   = s.harvest_id
join planting p  on p.planting_id  = h.planting_id
join farm     fm on fm.farm_id     = p.farm_id
join crop     c  on c.crop_id      = p.crop_id;

create view v_input_item_list with (security_invoker = true) as
select i.*, it.input_type_name, u.unit_code
from input_item i
join input_type      it on it.input_type_id = i.input_type_id
join unit_of_measure u  on u.unit_id        = i.unit_id;

create view v_input_usage_list with (security_invoker = true) as
select iu.*,
       fm.farm_id,
       fm.farm_name,
       c.crop_name,
       i.input_name,
       it.input_type_name,
       u.unit_code,
       round(iu.quantity * i.unit_cost, 2) as estimated_cost
from input_usage iu
join planting        p  on p.planting_id    = iu.planting_id
join farm            fm on fm.farm_id       = p.farm_id
join crop            c  on c.crop_id        = p.crop_id
join input_item      i  on i.input_id       = iu.input_id
join input_type      it on it.input_type_id = i.input_type_id
join unit_of_measure u  on u.unit_id        = i.unit_id;

create view v_profile_list with (security_invoker = true) as
select pr.*, r.role_name
from profile pr
join app_role r on r.role_id = pr.role_id;

create view v_audit_log_list with (security_invoker = true) as
select a.*, coalesce(pr.full_name, 'System / SQL editor') as changed_by_name
from audit_log a
left join profile pr on pr.user_id = a.changed_by;
