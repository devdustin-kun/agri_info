-- =====================================================================
-- Agriculture Information System  -  schema.sql
-- Database: Supabase PostgreSQL
--
-- RUN ORDER (Supabase > SQL Editor):
--   1. schema.sql    tables, constraints, indexes, triggers, list views
--   2. reports.sql   report / dashboard functions
--   3. security.sql  Row Level Security + privileges
--   4. seed.sql      lookup values + sample data
--
-- ---------------------------------------------------------------------
-- NORMALIZATION (short version - full tables are in README.md)
--
-- UNF  One spreadsheet row per farmer with repeating groups:
--      farmer + many farms + many plantings + many harvests, and text
--      columns such as "Grade A", "Irrigated", "Good harvest".
--
-- 1NF  Every cell atomic, no repeating groups. One row per harvest
--      event; the composite key is (farmer, farm, crop, planting_date,
--      harvest_date). Names are split into first_name / last_name.
--
-- 2NF  Remove PARTIAL dependencies (columns that depend on only part of
--      the composite key):
--        farmer facts depend only on the farmer      -> FARMER
--        farm facts depend only on the farm          -> FARM
--        crop facts depend only on the crop          -> CROP
--        planting facts depend on farm+crop+date     -> PLANTING
--        harvest facts depend on the harvest event   -> HARVEST
--      Each table gets a surrogate integer IDENTITY primary key.
--
-- 3NF  Remove TRANSITIVE dependencies (non-key -> non-key):
--      * Repeated descriptive text (category, season, soil type,
--        irrigation type, status, grade, remark, buyer type, input type,
--        unit, role) moves into LOOKUP tables. Main tables store only the
--        numeric ID as a FOREIGN KEY, and the UI shows the label in a
--        dropdown.
--      * Values that can be calculated are NOT stored:
--          estimated harvest value = quantity_kg * selling_price_per_kg
--          sale amount             = quantity_kg * price_per_kg
--          input cost              = quantity * input_item.unit_cost
--        They are computed in views / report functions instead.
--      * expected_harvest_date IS stored on purpose: it is a planning
--        estimate the user may adjust (weather, variety), not a value
--        that must always equal planting_date + growing_period_days.
--        The app pre-fills it from the crop's growing period.
-- =====================================================================


