-- =====================================================================
-- 3. CORE TABLES  (from the project brief)
--    Every core table carries audit columns:
--      created_at / updated_at  -> when
--      created_by / updated_by  -> which logged-in user (auth.uid())
--    They are filled by the trigger set_audit_fields(), so users cannot fake them.
-- =====================================================================

create table farmer (
  farmer_id       integer generated by default as identity primary key,
  first_name      varchar(50)  not null check (btrim(first_name) <> ''),
  last_name       varchar(50)  not null check (btrim(last_name)  <> ''),
  contact_number  varchar(20)  not null unique
                  check (contact_number ~ '^(09|\+639)[0-9]{9}$'),   -- PH mobile: 09XXXXXXXXX or +639XXXXXXXXX
  address         varchar(150) not null check (btrim(address) <> ''),
  date_registered date         not null default current_date
                  check (date_registered >= date '2000-01-01'),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null
);

create table farm (
  farm_id            integer generated by default as identity primary key,
  farmer_id          integer      not null references farmer(farmer_id) on delete restrict,
  farm_name          varchar(100) not null check (btrim(farm_name) <> ''),
  location           varchar(150) not null check (btrim(location)  <> ''),
  area_hectares      numeric(8,2) not null check (area_hectares > 0 and area_hectares <= 10000),
  soil_type_id       smallint     not null references soil_type(soil_type_id),
  irrigation_type_id smallint     not null references irrigation_type(irrigation_type_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  unique (farmer_id, farm_name)                 -- a farmer cannot have two farms with the same name
);

create table crop (
  crop_id             integer generated by default as identity primary key,
  crop_name           varchar(80) not null check (btrim(crop_name) <> ''),
  variety             varchar(80) not null check (btrim(variety)   <> ''),
  category_id         smallint    not null references crop_category(category_id),
  growing_period_days integer     not null check (growing_period_days between 1 and 1825),
  season_id           smallint    not null references season(season_id),   -- recommended season
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  unique (crop_name, variety)
);

create table planting (
  planting_id           integer generated by default as identity primary key,
  farm_id               integer      not null references farm(farm_id) on delete restrict,
  crop_id               integer      not null references crop(crop_id) on delete restrict,
  planting_date         date         not null,
  area_planted          numeric(8,2) not null check (area_planted > 0),
  seed_quantity         numeric(8,2) not null check (seed_quantity >= 0),   -- kg of seed / planting material
  expected_harvest_date date         not null,
  status_id             smallint     not null default 1 references planting_status(status_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  check (expected_harvest_date > planting_date)
);

create table harvest (
  harvest_id           integer generated by default as identity primary key,
  planting_id          integer       not null references planting(planting_id) on delete restrict,
  harvest_date         date          not null,
  quantity_kg          numeric(10,2) not null check (quantity_kg > 0),
  selling_price_per_kg numeric(10,2) not null check (selling_price_per_kg >= 0),
  grade_id             smallint      not null references quality_grade(grade_id),
  remark_id            smallint      not null references harvest_remark(remark_id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null
);


